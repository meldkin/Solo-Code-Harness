#!/usr/bin/env python3
"""
opencode_engine.py — OpenCode engine generator (OpenCode v2).

Reads .kilo/ (source of truth) and emits .opencode/ (agents, commands,
instructions) plus root opencode.json targeting the OpenCode **v2** schema.

History:
  .opencode/ was removed in v4.0.0, reintroduced in v4.2.0 for OpenCode v1.18.
  v1.18 shipped as npm `opencode-ai`; the v2 line ships as `@opencode/cli`
  (verified 2026-09-27: `opencode-ai` latest = 1.18.32, `@opencode/cli`
  latest = 2.0.18, plugin SDK `@opencode-ai/plugin` -> `@opencode/plugin`).
  The v2 config surface is not backward compatible, so this engine now emits
  v2 shapes only. See opencode.ai/v2/docs/{config,permissions,agents,providers,
  instructions}.

Transform rules (source -> OpenCode v2):
  - agents:   .kilo/agents/*.md   -> .opencode/agents/*.md
              Kilo's `permission:` object is rewritten to v2's ordered
              `permissions:` array. `bash` -> `shell`, `task` -> `subagent`,
              and `codesearch`/`mcp` are dropped (no v2 action). Within a
              permission map the exact `*` rule is emitted first so the more
              specific rules follow it: v2 resolves with last-match-wins,
              while Kilo resolves the most specific match.
  - commands: .kilo/command/*.md  -> .opencode/commands/*.md (verbatim)
  - skills:   NOT mirrored. OpenCode v2 loads `.opencode/skills/` AND the
              Claude-compatible `.claude/skills/` and `.agents/skills/`
              (docs: Skills > Discovery). Mirroring .kilo/skill into a second
              location would register every skill twice, so OpenCode relies on
              `.claude/skills/` (generated by claude_engine) and this engine
              prunes any legacy `.opencode/skills/` mirror.
              Skills whose frontmatter sets `disable-model-invocation: true`
              become `permission.skill[name] = "ask"` in opencode.json, since
              OpenCode ignores that Claude-only field (see collect_disabled_skills).
  - instructions: OpenCode v2 accepts an `instructions` config array but does
              not resolve it, and loads only `AGENTS.md` (docs: Instructions >
              Configuration). File-type rules should not bloat the
              always-loaded AGENTS.md, so `.kilo/instruction/*.md` become
              on-demand skills under `.opencode/skills/<id>/SKILL.md`, which v2
              advertises by description and loads only when relevant. Any
              legacy `.opencode/instruction/` mirror is pruned.
  - config:   split across two files because the host IDE's OpenCode v1
              (`kilo.exe`) strictly validates the root config and hard-rejects
              v2-only keys. Root `opencode.json` keeps only v1-safe keys
              (`$schema`, `model`, `small_model`, `default_agent`, `agents`,
              `permission`); `.opencode/opencode.json` carries the v2-only
              self-contained `commandcode` provider (replacing the retired v1
              plugin `commandcode-go-opencode-provider`). OpenCode v2 merges the
              local file with higher precedence; Kilo's validator ignores it.
              The permission gate uses the legacy `permission` object for the
              same reason (v2 maps and enforces it). Only the `commandcode/<id>`
              models the harness references are declared (_PROVIDER_MODELS).
"""

