def _write_if_changed(path: Path, content: str) -> None:
    """Write `content` as LF text, but only when it differs from what is there.

    An unconditional write bumps mtime, and `git status` then reports every
    generated artifact as modified while `git diff` shows nothing at all -- it
    compares stat first and only reads content on `git diff`. Mirrors the guard
    in claude_engine._write_lf.
    """
    if path.exists():
        with contextlib.suppress(OSError, UnicodeDecodeError):
            if path.read_text(encoding="utf-8") == content:
                return
    path.write_text(content, encoding="utf-8", newline="")


def _copy_if_changed(src: Path, dst: Path) -> None:
    """Copy `src` over `dst` only when the bytes actually differ."""
    data = src.read_bytes()
    if dst.exists():
        with contextlib.suppress(OSError):
            if dst.read_bytes() == data:
                return
    dst.write_bytes(data)


def _frontmatter_block(text: str) -> str | None:
    """Return the text between the opening and closing `---` fences, or None."""
    if not text.startswith("---"):
        return None
    end = text.find("\n---", 3)
    if end == -1:
        return None
    return text[3:end]


def collect_disabled_skills(kilo_root: Path) -> dict[str, str]:
    """Map skill name -> permission action for skills marked
    `disable-model-invocation: true` in .kilo/skill/<name>/SKILL.md.
    """
    out: dict[str, str] = {}
    skill_root = kilo_root / "skill"
    if not skill_root.is_dir():
        return out
    for skill_dir in sorted(p for p in skill_root.iterdir() if p.is_dir()):
        skill_md = skill_dir / "SKILL.md"
        if not skill_md.is_file():
            continue
        fm = _frontmatter_block(skill_md.read_text(encoding="utf-8"))
        if fm is None:
            continue
        for line in fm.splitlines():
            key, _, value = line.partition(":")
            if key.strip() == "disable-model-invocation" and value.strip().lower() == "true":
                out[skill_dir.name] = _DISABLED_SKILL_PERMISSION
                break
    return out


def _parse_permission_block(frontmatter: str) -> tuple[list[str], list[tuple[str, list[tuple[str, str]]]]]:
    """Split an agent frontmatter into (kept lines, permission entries).

    `kept lines` are every frontmatter line outside the `permission:` block,
    preserved verbatim and in order. `permission entries` are ordered
    (action, [(resource, effect), ...]) pairs; a scalar permission such as
    `edit: allow` becomes a single `("*", "allow")` rule.
    """
    kept: list[str] = []
    entries: list[tuple[str, list[tuple[str, str]]]] = []
    lines = frontmatter.split("\n")
    i = 0
    while i < len(lines):
        raw = lines[i]
        if raw.strip() != "permission:":
            kept.append(raw)
            i += 1
            continue

        # Collect the permission block's child lines until the next dedent.
        children: list[tuple[int, str, str | None]] = []
        i += 1
        while i < len(lines):
            nxt = lines[i]
            if not nxt.strip():
                i += 1
                continue
            indent = len(nxt) - len(nxt.lstrip(" "))
            if indent == 0:
                break
            key, sep, value = nxt.strip().partition(":")
            key = key.strip().strip('"').strip("'")
            children.append((indent, key, value.strip() if sep else None))
            i += 1

        idx = 0
        while idx < len(children):
            indent, key, value = children[idx]
            if value:
                entries.append((key, [("*", value)]))
                idx += 1
                continue
            rules: list[tuple[str, str]] = []
            idx += 1
            while idx < len(children) and children[idx][0] > indent:
                _, resource, effect = children[idx]
                rules.append((resource, effect or ""))
                idx += 1
            entries.append((key, rules))

    while kept and not kept[-1].strip():
        kept.pop()
    return kept, entries


def _render_permissions(entries: list[tuple[str, list[tuple[str, str]]]]) -> list[str]:
    """Render permission entries as a v2 `permissions:` YAML block sequence.

    The exact `*` rule is emitted before the rest so specific rules win under
    v2's last-match-wins resolution.
    """
    rules: list[tuple[str, str, str]] = []
    for action, children in entries:
        if action in _DROP_PERMISSION_KEYS:
            continue
        mapped = _PERMISSION_ACTION_RENAME.get(action, action)
        ordered = [c for c in children if c[0] == "*"] + [c for c in children if c[0] != "*"]
        for resource, effect in ordered:
            if not effect:
                continue
            rules.append((mapped, resource, effect))
    if not rules:
        return []
    out = ["permissions:"]
    for action, resource, effect in rules:
        out.append(f"  - action: {action}")
        out.append(f'    resource: "{resource}"')
        out.append(f"    effect: {effect}")
    return out


def _convert_agent_frontmatter(frontmatter: str) -> str:
    kept, entries = _parse_permission_block(frontmatter)
    rendered = kept + _render_permissions(entries)
    return "\n".join(rendered).rstrip("\n")


def generate_agents(kilo_root: Path, opencode_root: Path) -> int:
    src_dir = kilo_root / "agents"
    dst_dir = opencode_root / "agents"
    if not src_dir.is_dir():
        print(f"[ERROR] Source agent directory not found: {src_dir}")
        return 1
    dst_dir.mkdir(parents=True, exist_ok=True)
    copied = 0
    for agent_file in sorted(src_dir.glob("*.md")):
        content = agent_file.read_text(encoding="utf-8")
        split = content.split("---", 2)
        if len(split) < 3:
            print(f"  [SKIP] agents/{agent_file.name} (no frontmatter)")
            continue
        fm = _convert_agent_frontmatter(split[1].strip("\n"))
        body = split[2].lstrip("\n")
        new_content = f"---\n{fm}\n---\n{body}"
        _write_if_changed(dst_dir / agent_file.name, new_content)
        copied += 1
        print(f"  [GEN] agents/{agent_file.name}")
    print(f"OpenCode agents generated: {copied}")
    return 0


